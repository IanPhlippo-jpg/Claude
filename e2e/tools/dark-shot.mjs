// Screenshot of the dark theme with a part and the Feature Tree (compare with the original's dark mode).
import { chromium } from 'playwright';
import { mkdirSync } from 'node:fs';

const OUT = process.env.E2E_OUT ?? (process.platform === 'win32' ? 'e2e-out' : '/tmp/phlippo-e2e');
mkdirSync(OUT, { recursive: true });
const browser = await chromium.launch(process.platform === 'win32' ? { channel: process.env.PW_CHANNEL ?? 'msedge' } : { ...(process.env.PW_CHROMIUM ? { executablePath: process.env.PW_CHROMIUM } : {}), args: ['--use-gl=swiftshader', '--enable-unsafe-swiftshader'] });
const page = await browser.newPage({ viewport: { width: 1920, height: 1080 }, deviceScaleFactor: 1, colorScheme: 'dark' });
await page.goto(process.env.E2E_URL ?? 'http://localhost:4173/');
await page.evaluate(() => { localStorage.clear(); localStorage.setItem('phlippo.theme', 'dark'); });
await page.reload();
await page.waitForSelector('.k-viewport');
await page.waitForTimeout(500);
await page.click('.k-doctype:has-text("Part")');
await page.click('.k-tree-row:has-text("Top Plane")');
await page.click('.k-cm-tab:has-text("Sketch")');
await page.click('.k-cm-big:has-text("Sketch") .k-cm-main');
await page.waitForTimeout(400);
const vp = await page.locator('.k-viewport').boundingBox();
const cx = vp.x + vp.width / 2, cy = vp.y + vp.height / 2;
await page.click('.k-cm-iconbtn[data-tip="Corner Rectangle"]');
await page.mouse.click(cx - 150, cy - 100);
await page.mouse.click(cx + 150, cy + 100);
await page.keyboard.press('Escape');
await page.click('.k-cm-big:has-text("Smart Dimension") .k-cm-main');
await page.mouse.click(cx, cy + 100);
await page.mouse.click(cx, cy + 160);
await page.waitForTimeout(200);
await page.locator('.k-modify input.k-num').fill('60');
await page.locator('.k-modify input.k-num').press('Enter');
await page.keyboard.press('Escape');
await page.keyboard.press('Escape');
await page.screenshot({ path: `${OUT}/dark-sketch.png` });
await page.click('.k-cm-tab:has-text("Features")');
await page.click('.k-cm-big:has-text("Extruded Boss/Base") .k-cm-main');
await page.waitForTimeout(400);
await page.screenshot({ path: `${OUT}/dark-extrude-pm.png` });
await page.click('.k-pm-ok');
await page.waitForTimeout(600);
await page.keyboard.press('f');
await page.waitForTimeout(400);
await page.screenshot({ path: `${OUT}/dark-part.png` });
await browser.close();
console.log('dark shots done');
