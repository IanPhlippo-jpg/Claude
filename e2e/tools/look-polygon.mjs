// look-dev: Polygon tool: a hexagon with its construction circle, relations
import { chromium } from 'playwright';
const browser = await chromium.launch(process.platform === 'win32' ? { channel: process.env.PW_CHANNEL ?? 'msedge' } : { ...(process.env.PW_CHROMIUM ? { executablePath: process.env.PW_CHROMIUM } : {}), args: ['--use-gl=swiftshader', '--enable-unsafe-swiftshader'] });
const page = await browser.newPage({ viewport: { width: 1920, height: 1080 } });
const errors = [];
page.on('pageerror', (e) => errors.push(e.message));
await page.goto(process.env.E2E_URL ?? 'http://127.0.0.1:5173/');
await page.evaluate(() => { localStorage.clear(); localStorage.setItem('phlippo.theme', 'light'); });
await page.reload();
await page.waitForSelector('.k-viewport');
await page.click('.k-doctype:has-text("Part")');
await page.evaluate(() => { window.__phlippoStore.getState().newSketch('front'); });
await page.waitForTimeout(800);
await page.evaluate(() => window.__phlippoStore.getState().setTool('polygon'));
await page.waitForTimeout(300);
const o = await page.evaluate(() => window.__phlippoProjectWorld(0, 0, 0));
const v = await page.evaluate(() => window.__phlippoProjectWorld(0, 30, 0));
await page.mouse.move(o.x, o.y);
await page.mouse.click(o.x, o.y);
await page.mouse.move(v.x - 10, v.y + 5, { steps: 5 });
await page.waitForTimeout(300);
await page.screenshot({ path: 'e2e-out/look-polygon1.png' });
await page.mouse.click(v.x, v.y);
await page.waitForTimeout(500);
await page.mouse.move(400, 900);
await page.waitForTimeout(300);
await page.screenshot({ path: 'e2e-out/look-polygon2.png' });
console.log(errors);
await browser.close();
