// Section View options: Section 2 (quarter cut), cap colour, graphics-only, zonal, selected bodies, Save.
import { chromium } from 'playwright';
import { exitCode } from './lib/check.mjs';
import { mkdirSync, readFileSync } from 'node:fs';

const OUT = process.env.E2E_OUT ?? (process.platform === 'win32' ? 'e2e-out' : '/tmp/phlippo-e2e');
mkdirSync(OUT, { recursive: true });
const browser = await chromium.launch(process.platform === 'win32' ? { channel: process.env.PW_CHANNEL ?? 'msedge' } : { ...(process.env.PW_CHROMIUM ? { executablePath: process.env.PW_CHROMIUM } : {}), args: ['--use-gl=swiftshader', '--enable-unsafe-swiftshader'] });
const page = await browser.newPage({ viewport: { width: 1920, height: 1080 }, deviceScaleFactor: 1, colorScheme: 'light' });
const errors = [];
const results = [];
const check = (name, ok, info = '') => { results.push({ name, ok: !!ok, info }); if (!ok) console.log('FAIL', name, info); };
page.on('pageerror', (e) => errors.push('pageerror: ' + e.message + (e.stack ? ' | ' + String(e.stack).split(/\r?\n/).slice(1, 3).join(' <- ').replace(/\s+/g, ' ') : '')));
page.on('console', (m) => { if (m.type() === 'error') errors.push('console: ' + m.text()); });
const shot = (n) => page.screenshot({ path: `${OUT}/${n}.png` });

await page.goto(process.env.E2E_URL ?? 'http://localhost:4173/');
await page.evaluate(() => { localStorage.clear(); localStorage.setItem('phlippo.theme', 'light'); });
await page.reload();
await page.waitForSelector('.k-viewport');
await page.waitForTimeout(500);
await page.click('.k-doctype:has-text("Part")');
const part = JSON.parse(readFileSync('voorbeelden/deurkruk/Rozet.kcad', 'utf8'));
delete part.format;
await page.evaluate((d) => window.__phlippoStore.getState().openDocument(d), part);
await page.waitForTimeout(800);
await page.evaluate(() => window.__phlippoStore.getState().startSectionView());
await page.waitForTimeout(300);
check('Section View PM', (await page.locator('[data-testid="section-pm"]').count()) === 1);
const caps = () => page.evaluate(() => window.__phlippoStore.getState().sectionEdit);
await page.click('[data-testid="section-pm"] .k-section-title:has-text("Section 2") .k-section-check');
await page.waitForTimeout(600);
let se = await caps();
check('Section 2 on (Top Plane)', se.s2 && se.s2.plane === 'top', JSON.stringify(se.s2));
await page.locator('[data-testid="section-capcolor"]').evaluate((el) => { const set = Object.getOwnPropertyDescriptor(HTMLInputElement.prototype, 'value').set; set.call(el, '#ff8800'); el.dispatchEvent(new Event('input', { bubbles: true })); el.dispatchEvent(new Event('change', { bubbles: true })); });
await page.waitForTimeout(500);
se = await caps();
check('Edit Color sets the cap colour', se.capColor === '#ff8800', se.capColor);
await shot('so1-quarter-cap');
await page.click('[data-testid="section-zonal"]');
await page.waitForTimeout(600);
await shot('so2-zonal');
await page.click('[data-testid="section-gpu"]');
await page.waitForTimeout(500);
await shot('so3-graphics-only');
await page.click('[data-testid="section-pm"] .k-section-title:has-text("Drawing Section View")');
await page.click('[data-testid="section-save"]');
await page.waitForTimeout(200);
const saved = await page.evaluate(() => (window.__phlippoStore.getState().doc.sectionViews ?? []).map((v) => v.name));
check('Save stores Section View1', saved[0] === 'Section View1', JSON.stringify(saved));
await page.click('[data-testid="section-pm"] .k-pm-ok');
await page.waitForTimeout(300);
check('section committed', await page.evaluate(() => !!window.__phlippoStore.getState().sectionView));
console.log(results.filter((r) => r.ok).length + '/' + results.length + ' passed');
process.exitCode = exitCode(results, errors);
if (errors.length) console.log('ERRORS', errors.slice(0, 5));
await browser.close();
