// look-dev at Ian's screen: 1920 x 1080 at 150 % (1280 x 672 CSS px in the maximized window, device pixel ratio 1.5).
// Screens: part (door handle), sketch with rectangle, Boss-Extrude PM, assembly, drawing -> e2e-out/ian-*.png
import { chromium } from 'playwright';
import { readFileSync } from 'node:fs';
const browser = await chromium.launch({ channel: process.env.PW_CHANNEL ?? 'msedge' });
const page = await browser.newPage({ viewport: { width: 1280, height: 672 }, deviceScaleFactor: 1.5, colorScheme: 'light' });
const errors = [];
page.on('pageerror', (e) => errors.push('pageerror: ' + e.message));
page.on('console', (m) => { if (m.type() === 'error') errors.push('console: ' + m.text()); });
await page.goto(process.env.E2E_URL ?? 'http://127.0.0.1:4173/');
await page.evaluate(() => { localStorage.clear(); localStorage.setItem('phlippo.theme', 'light'); });
await page.reload();
await page.waitForSelector('.k-viewport');
await page.waitForTimeout(800);
await page.screenshot({ path: 'e2e-out/ian-welcome.png' });
await page.click('.k-doctype:has-text("Part")');
await page.waitForTimeout(600);
await page.screenshot({ path: 'e2e-out/ian-empty-part.png' });
// sketch with a rectangle
await page.click('.k-cm-tab:has-text("Sketch")');
await page.evaluate(() => window.__phlippoStore.getState().newSketch('front'));
await page.waitForTimeout(1200);
await page.evaluate(() => window.__phlippoStore.getState().setTool('rectangle'));
const vp = await page.locator('.k-viewport').boundingBox();
const cx = vp.x + vp.width / 2, cy = vp.y + vp.height / 2;
await page.mouse.click(cx - 120, cy + 70);
await page.mouse.click(cx + 120, cy - 70);
await page.waitForTimeout(400);
await page.screenshot({ path: 'e2e-out/ian-sketch.png' });
await page.keyboard.press('Escape');
await page.click('.k-cm-tab:has-text("Features")');
await page.click('.k-cm-big:has-text("Extruded Boss/Base") .k-cm-main');
await page.waitForTimeout(900);
await page.screenshot({ path: 'e2e-out/ian-extrude-pm.png' });
await page.screenshot({ path: 'e2e-out/ian-extrude-crop.png', clip: { x: 600, y: 270, width: 260, height: 230 } });
await page.click('.k-pm-ok').catch(() => undefined);
await page.waitForTimeout(900);
await page.screenshot({ path: 'e2e-out/ian-part.png' });
// door handle assembly
const asm = JSON.parse(readFileSync('voorbeelden/deurkruk/Deurkruk.kcad', 'utf8')); delete asm.format;
await page.evaluate((d) => window.__phlippoStore.getState().openDocument(d), asm);
await page.waitForTimeout(2500);
await page.keyboard.press('Control+7');
await page.keyboard.press('f');
await page.mouse.move(5, 660);
await page.waitForTimeout(1200);
await page.screenshot({ path: 'e2e-out/ian-assembly.png' });
const drw = JSON.parse(readFileSync('voorbeelden/deurkruk/Deurkruk-tekening.kcad', 'utf8')); delete drw.format;
await page.evaluate((d) => window.__phlippoStore.getState().openDocument(d), drw);
await page.waitForTimeout(3000);
await page.screenshot({ path: 'e2e-out/ian-drawing.png' });
console.log('errors:', errors.length ? errors : 'none');
await browser.close();
